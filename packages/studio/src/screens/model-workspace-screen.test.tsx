import { exportGlb } from '@ai3d/editor';
import type { ModelRead, ModelVersionRead } from '@ai3d/shared-types';
import { parseGlb } from '@ai3d/viewer';
import { fireEvent, screen, waitFor, within } from '@testing-library/react';
import * as THREE from 'three';

import { fakeApi, renderWithStudio } from '../test/render';
import { ModelWorkspaceScreen } from './model-workspace-screen';

const version: ModelVersionRead = {
  id: 'v1',
  model_id: 'm1',
  version_number: 1,
  parent_version_id: null,
  source: 'generated',
  quality_mode: 'fast',
  provider_key: 'tripo',
  provider_display_name: 'Tripo AI',
  surface_provenance: 'inferred',
  stats: {},
  notes: 'Generated by Tripo AI from 1 photo.',
  job_id: 'j1',
  mesh: { format: 'glb', mime_type: 'model/gltf-binary', size_bytes: 2048, sha256: 'x' },
  has_preview: false,
  quality_report: {
    status: 'pass',
    report_version: 1,
    metrics: { watertight: true, components: 1, degenerate_triangles: 0, has_uv: false },
    issues: [],
    created_at: '2026-11-03T10:00:00Z',
  },
  created_at: '2026-11-03T10:00:00Z',
  file_url: '/api/v1/model-versions/v1/file',
  preview_url: null,
};

const model: ModelRead = {
  id: 'm1',
  project_id: 'p1',
  name: 'Tripo AI · Fast',
  created_at: '2026-11-03T10:00:00Z',
  updated_at: '2026-11-03T10:00:00Z',
  current_version: version,
  version_count: 1,
};

async function sampleGlb(): Promise<ArrayBuffer> {
  const body = new THREE.Mesh(
    new THREE.BoxGeometry(0.2, 0.3, 0.2),
    new THREE.MeshStandardMaterial({ name: 'Glaze', color: 0x336699 }),
  );
  body.name = 'Body';
  const root = new THREE.Group();
  root.add(body);
  return exportGlb(root);
}

const older: ModelVersionRead = {
  ...version,
  id: 'v0',
  version_number: 0,
  notes: 'An older version.',
};

function setup(versions: ModelVersionRead[] = [version]) {
  const api = fakeApi({
    projects: { get: vi.fn().mockResolvedValue({ id: 'p1', name: 'Mug' }) },
    models: {
      get: vi.fn().mockResolvedValue(model),
      versions: vi.fn().mockResolvedValue({ items: versions, current_version_id: 'v1' }),
      saveVersion: vi.fn().mockResolvedValue({ ...version, id: 'v2', version_number: 2 }),
      update: vi.fn(),
    },
  });
  return renderWithStudio(<ModelWorkspaceScreen projectId="p1" modelId="m1" />, api);
}

beforeEach(async () => {
  const glb = await sampleGlb();
  vi.stubGlobal(
    'fetch',
    vi.fn().mockImplementation(async () => new Response(glb.slice(0), { status: 200 })),
  );
});

afterEach(() => {
  vi.unstubAllGlobals();
});

describe('ModelWorkspaceScreen', () => {
  it('opens the stored file and reports real facts about it', async () => {
    setup();
    // jsdom has no WebGL: the view explains itself instead of failing.
    expect(await screen.findByText('3D view unavailable')).toBeInTheDocument();
    expect(fetch).toHaveBeenCalledWith(
      'http://api/api/v1/model-versions/v1/file',
      expect.anything(),
    );

    const hierarchy = screen.getByRole('list', { name: 'Model hierarchy' });
    expect(within(hierarchy).getByRole('button', { name: /^Body/ })).toBeInTheDocument();
    const inspector = screen.getByRole('complementary', { name: 'Inspector' });
    expect(within(inspector).getByText('Triangles').nextSibling).toHaveTextContent('12');
    expect(within(inspector).getByText('Height (Y)').nextSibling).toHaveTextContent('0.3 units');
    expect(within(inspector).getByText(/no real-world scale/)).toBeInTheDocument();
    expect(
      within(inspector).getByText('AI-generated: unseen surfaces invented'),
    ).toBeInTheDocument();
  });

  it('edits a part, undoes, redoes and saves the result as a new version', async () => {
    const { api } = setup();
    const hierarchy = await screen.findByRole('list', { name: 'Model hierarchy' });
    fireEvent.click(within(hierarchy).getByRole('button', { name: /^Body/ }));
    expect(screen.getByTestId('selection-name')).toHaveTextContent('Body');

    const save = screen.getByRole('button', { name: /Save as version 2/ });
    expect(save).toBeDisabled();

    const x = screen.getByRole('spinbutton', { name: 'Position X' });
    fireEvent.change(x, { target: { value: '2' } });
    fireEvent.keyDown(x, { key: 'Enter' });

    const undo = screen.getByRole('button', { name: 'Undo: Moved "Body"' });
    expect(save).toBeEnabled();
    expect(screen.getByText(/Unsaved edits/)).toBeInTheDocument();

    fireEvent.click(undo);
    expect(save).toBeDisabled();
    expect(screen.getByRole('spinbutton', { name: 'Position X' })).toHaveValue(0);
    fireEvent.keyDown(window, { key: 'z', ctrlKey: true, shiftKey: true }); // redo
    expect(screen.getByRole('spinbutton', { name: 'Position X' })).toHaveValue(2);

    fireEvent.click(save);
    await waitFor(() => expect(api.models.saveVersion).toHaveBeenCalledTimes(1));
    const [modelId, file, meta] = vi.mocked(api.models.saveVersion).mock.calls[0]!;
    expect(modelId).toBe('m1');
    expect(meta).toEqual({ parentVersionId: 'v1', changes: ['Moved "Body"'] });

    // What was uploaded is a real GLB with the edit applied.
    const saved = await parseGlb(await (file as Blob).arrayBuffer());
    expect(saved.root.getObjectByName('Body')?.position.x).toBe(2);
  });

  it('asks before discarding unsaved edits when switching versions', async () => {
    setup([version, older]);
    const hierarchy = await screen.findByRole('list', { name: 'Model hierarchy' });
    fireEvent.click(within(hierarchy).getByRole('button', { name: /^Body/ }));
    const y = screen.getByRole('spinbutton', { name: 'Scale Y' });
    fireEvent.change(y, { target: { value: '3' } });
    fireEvent.blur(y);
    expect(screen.getByRole('button', { name: 'Undo: Scaled "Body"' })).toBeEnabled();

    fireEvent.click(screen.getByRole('tab', { name: /Versions \(2\)/ }));
    const list = screen.getByRole('list', { name: 'Version history' });
    expect(within(list).getByText('Current')).toBeInTheDocument();
    expect(within(list).getByText('Viewing')).toBeInTheDocument();

    fireEvent.click(within(list).getByRole('button', { name: 'View' }));
    expect(
      await screen.findByRole('alertdialog', { name: 'Discard unsaved edits?' }),
    ).toBeVisible();
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }));
    // Still on version 1 with the edit intact.
    expect(screen.getByRole('button', { name: 'Undo: Scaled "Body"' })).toBeEnabled();
    expect(within(list).getByText('Viewing').closest('li')).toHaveTextContent('Version 1');
  });
});
