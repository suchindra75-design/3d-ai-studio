log = logging.getLogger(__name__)

GLB_MIME = "model/gltf-binary"
_CHUNK = 1024 * 1024
MAX_CHANGES = 200
MAX_CHANGE_LENGTH = 200
QUALITY_LABELS = {
    QualityMode.FAST: "Fast",
    QualityMode.HIGH_QUALITY: "High quality",
    QualityMode.PROFESSIONAL: "Professional",
}
_STAT_KEYS = (
    "vertex_count",
    "triangle_count",
    "mesh_count",
    "material_count",
    "texture_count",
    "has_uv",
    "bbox_size",
    "watertight",
    "components",
)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def _generation_notes(provider: type[Provider], job: GenerationJob) -> str:
    if provider.kind == ProviderKind.MOCK:
        return (
            "Placeholder sphere from the test provider. It is not a reconstruction of your photos."
        )
    count = len(job.inputs)
    if job.kind == JobKind.IMAGE_TO_3D:
        return (
            f"Generated by {provider.display_name} from 1 photo. Surfaces the camera did not see "
            "were invented by the AI model. Shape and size are not measurements of the real "
            "object."
        )
    return (
        f"Generated by {provider.display_name} from {count} photos. Surfaces between and "
        "beyond the views were inferred by the AI model. Shape and size are not measurements "
        "of the real object."
    )


def save_generated_model(
    db: Session,
    storage: StorageBackend,
    settings: Settings,
    *,
    job: GenerationJob,
    provider: type[Provider],
    result: ProviderResult,
    report: MeshReport,
) -> ModelVersion:
    """Store the downloaded file as version 1 of a new model, with its quality report."""
    project = get_project(db, job.project_id)
    model_id = uuid.uuid4()
    mesh_key = model_asset_key(project.id, model_id, 1, "model.glb")
    preview_key = model_asset_key(project.id, model_id, 1, "preview.webp")
    preview_bytes: bytes | None = None
    if result.preview_path is not None:
        try:
            with imgproc.open_validated(
                result.preview_path, max_pixels=settings.max_image_pixels
            ) as img:
                meta = imgproc.extract_metadata(img)
                preview_bytes = imgproc.make_thumbnail(
                    img, size=settings.thumbnail_size, has_alpha=meta.has_alpha
                )
        except (AppError, OSError):
            log.info("provider preview image ignored", extra={"job_id": str(job.id)})

    try:
        storage.save_file(mesh_key, result.mesh_path)
        if preview_bytes is not None:
            storage.save_bytes(preview_key, preview_bytes)

        model = Model3D(
            id=model_id,
            project_id=project.id,
            name=f"{provider.display_name} · {QUALITY_LABELS[job.quality_mode]}",
        )
        db.add(model)
        db.flush()
        version = ModelVersion(
            model_id=model_id,
            version_number=1,
            job_id=job.id,
            source=ModelVersionSource.GENERATED,
            quality_mode=job.quality_mode,
            provider_key=provider.key,
            surface_provenance=SurfaceProvenance.INFERRED,
            stats={k: report.metrics.get(k) for k in _STAT_KEYS},
            notes=_generation_notes(provider, job),
        )
        db.add(version)
        db.flush()
        mesh = Asset(
            project_id=project.id,
            model_version_id=version.id,
            kind=AssetKind.MESH,
            storage_key=mesh_key,
            mime_type=GLB_MIME,
            size_bytes=result.mesh_path.stat().st_size,
            sha256=_sha256(result.mesh_path),
            meta={"format": result.mesh_format, "origin": "provider_output", **result.metadata},
        )
        db.add(mesh)
        if preview_bytes is not None:
            db.add(
                Asset(
                    project_id=project.id,
                    model_version_id=version.id,
                    kind=AssetKind.PREVIEW_IMAGE,
                    storage_key=preview_key,
                    mime_type="image/webp",
                    size_bytes=len(preview_bytes),
                    sha256=hashlib.sha256(preview_bytes).hexdigest(),
                    meta={"origin": "provider_render"},
                )
            )
        db.add(
            QualityReport(
                model_version_id=version.id,
                job_id=job.id,
                status=report.status,
                report_version=REPORT_VERSION,
                metrics=report.metrics,
                issues=[issue.to_dict() for issue in report.issues],
            )
        )
        db.flush()
        version.primary_asset_id = mesh.id
        model.current_version_id = version.id
        touch_project(db, project.id)
        db.commit()
    except BaseException:
        db.rollback()
        storage.delete_prefix(model_prefix(project.id, model_id))
        raise
    return version


# -- photogrammetry ----------------------------------------------------------------


def _reconstruction_notes(result: ReconstructionResult) -> str:
    used = len(result.registered)
    surface = (
        "The surface is dense."
        if result.dense
        else "Without a CUDA GPU the surface was built from sparse points, so it is coarse."
    )
    return (
        f"Reconstructed on this computer with COLMAP from {used} of {result.total_images} "
        f"photos. {surface} The shape is measured from the photos; areas no photo saw are "
        "open. The size is not to scale: photogrammetry recovers shape, not size, without a "
        "reference object."
    )


def save_reconstructed_model(
    db: Session,
    storage: StorageBackend,
    *,
    job: GenerationJob,
    glb_path: Path,
    points_path: Path,
    report: MeshReport,
    result: ReconstructionResult,
) -> ModelVersion:
    """Store a local reconstruction as version 1 of a new model, with its point cloud."""
    project = get_project(db, job.project_id)
    model_id = uuid.uuid4()
    mesh_key = model_asset_key(project.id, model_id, 1, "model.glb")
    points_key = model_asset_key(project.id, model_id, 1, "points.ply")
    metrics = {**report.metrics, "reconstruction": result.metrics()}
    issues = [
        *(issue.to_dict() for issue in report.issues),
        *(
            {"code": f"reconstruction_warning_{n}", "severity": "warning", "message": text}
            for n, text in enumerate(result.warnings)
        ),
        *(
            {"code": f"reconstruction_note_{n}", "severity": "info", "message": text}
            for n, text in enumerate(result.notes)
        ),
    ]
    try:
        storage.save_file(mesh_key, glb_path)
        storage.save_file(points_key, points_path)
        model = Model3D(
            id=model_id,
            project_id=project.id,
            name=f"Photogrammetry · {len(result.registered)} photos",
        )
        db.add(model)
        db.flush()
        version = ModelVersion(
            model_id=model_id,
            version_number=1,
            job_id=job.id,
            source=ModelVersionSource.RECONSTRUCTED,
            quality_mode=job.quality_mode,
            provider_key=job.provider_key,
            surface_provenance=SurfaceProvenance.MEASURED,
            stats={k: report.metrics.get(k) for k in _STAT_KEYS},
            notes=_reconstruction_notes(result),
        )
        db.add(version)
        db.flush()
        mesh = Asset(
            project_id=project.id,
            model_version_id=version.id,
            kind=AssetKind.MESH,
            storage_key=mesh_key,
            mime_type=GLB_MIME,
            size_bytes=glb_path.stat().st_size,
            sha256=_sha256(glb_path),
            meta={"format": "glb", "origin": "colmap", "textured": result.textured},
        )
        db.add(mesh)
        db.add(
            Asset(
                project_id=project.id,
                model_version_id=version.id,
                kind=AssetKind.POINT_CLOUD,
                storage_key=points_key,
                mime_type="application/octet-stream",
                size_bytes=points_path.stat().st_size,
                sha256=_sha256(points_path),
                meta={"format": "ply", "points": result.point_count, "frame": "upright"},
            )
        )
        db.add(
            QualityReport(
                model_version_id=version.id,
                job_id=job.id,
                status=report.status,
                report_version=REPORT_VERSION,
                metrics=metrics,
                issues=issues,
            )
        )
        db.flush()
        version.primary_asset_id = mesh.id
        model.current_version_id = version.id
        touch_project(db, project.id)
        db.commit()
    except BaseException:
        db.rollback()
        storage.delete_prefix(model_prefix(project.id, model_id))
        raise
    return version


# -- enhanced versions ---------------------------------------------------------------


def _next_version_number(db: Session, model_id: uuid.UUID) -> int:
    latest = db.scalar(
        select(func.max(ModelVersion.version_number)).where(ModelVersion.model_id == model_id)
    )
    return (latest or 0) + 1


def save_enhanced_version(
    db: Session,
    storage: StorageBackend,
    *,
    job: GenerationJob,
    parent: ModelVersion,
    glb_path: Path,
    report: MeshReport,
    steps: list[dict[str, str]],
    scale: dict[str, Any] | None,
) -> ModelVersion:
    """Store a processed GLB as a new ``enhanced`` version; the parent is kept."""
    model = get_model(db, parent.model_id)
    number = _next_version_number(db, model.id)
    key = model_asset_key(model.project_id, model.id, number, "model.glb")
    done = [s["title"] for s in steps if s["status"] == "applied"]
    known_scale = scale or (parent.stats or {}).get("scale")
    caveat = {
        SurfaceProvenance.INFERRED: " The geometry is still AI-generated: surfaces the camera "
        "did not see were invented.",
        SurfaceProvenance.MIXED: " Parts of the geometry were inferred rather than measured.",
    }.get(parent.surface_provenance, "")
    size = (
        " Size set from your measurement."
        if scale
        else " Real-world scale inherited from the parent version."
        if known_scale
        else " The size is still not to scale."
    )
    notes = (
        f"Enhanced from version {parent.version_number} "
        f"({QUALITY_LABELS[job.quality_mode]}): {', '.join(done) or 'no changes'}."
        f"{caveat}{size}"
    )
    storage.save_file(key, glb_path)
    try:
        stats: dict[str, Any] = {k: report.metrics.get(k) for k in _STAT_KEYS}
        if known_scale:
            stats["scale"] = known_scale
        version = ModelVersion(
            model_id=model.id,
            version_number=number,
            parent_version_id=parent.id,
            job_id=job.id,
            source=ModelVersionSource.ENHANCED,
            quality_mode=job.quality_mode,
            provider_key=parent.provider_key,
            surface_provenance=parent.surface_provenance,
            stats=stats,
            notes=notes,
        )
        db.add(version)
        db.flush()
        mesh = Asset(
            project_id=model.project_id,
            model_version_id=version.id,
            kind=AssetKind.MESH,
            storage_key=key,
            mime_type=GLB_MIME,
            size_bytes=glb_path.stat().st_size,
            sha256=_sha256(glb_path),
            meta={"format": "glb", "origin": "enhance"},
        )
        db.add(mesh)
        db.add(
            QualityReport(
                model_version_id=version.id,
                job_id=job.id,
                status=report.status,
                report_version=REPORT_VERSION,
                metrics={**report.metrics, "enhancement": steps},
                issues=[issue.to_dict() for issue in report.issues],
            )
        )
        db.flush()
        version.primary_asset_id = mesh.id
        model.current_version_id = version.id
        touch_project(db, model.project_id)
        db.commit()
    except BaseException:
        db.rollback()
        storage.delete(key)
        raise
    return version


# -- edited versions ------------------------------------------------------------


def _spool_model(stream: BinaryIO, target: Path, max_bytes: int) -> int:
    size = 0
    with target.open("wb") as out:
        while chunk := stream.read(_CHUNK):
            size += len(chunk)
            if size > max_bytes:
                raise PayloadTooLargeError(
                    f"Model exceeds the {max_bytes // (1024 * 1024)} MB limit.",
                    details={"max_model_bytes": max_bytes},
                )
            out.write(chunk)
    if size == 0:
        raise AppError("File is empty.", code="empty_file", status_code=422)
    return size


def _clean_changes(changes: list[str]) -> list[str]:
    cleaned = [" ".join(c.split())[:MAX_CHANGE_LENGTH] for c in changes]
    return [c for c in cleaned if c][:MAX_CHANGES]


def _edited_notes(parent: ModelVersion, changes: list[str]) -> str:
    summary = "; ".join(changes) if changes else "no changes recorded"
    caveat = {
        SurfaceProvenance.INFERRED: " The geometry is still AI-generated: surfaces the camera "
        "did not see were invented, and shape and size are not measurements.",
        SurfaceProvenance.MIXED: " Parts of the geometry were inferred rather than measured.",
    }.get(parent.surface_provenance, "")
    return f"Edited in the workspace from version {parent.version_number}: {summary}.{caveat}"


def add_edited_version(
    db: Session,
    storage: StorageBackend,
    settings: Settings,
    *,
    model_id: uuid.UUID,
    parent_version_id: uuid.UUID,
    stream: BinaryIO,
    changes: list[str],
) -> ModelVersion:
    """Store a GLB exported from the workspace as a new version; the parent is kept.

    The file is re-opened and checked exactly like provider output; a file that
    fails the checks is rejected and nothing is stored.
    """
    model = get_model(db, model_id)
    parent = get_version(db, parent_version_id)
    if parent.model_id != model.id:
        raise InvalidInputError(
            "The parent version belongs to a different model.",
            details={"parent_version_id": str(parent_version_id)},
        )
    changes = _clean_changes(changes)

    tmp_root = settings.data_dir / "tmp"
    tmp_root.mkdir(parents=True, exist_ok=True)
    workdir = Path(tempfile.mkdtemp(prefix="model-", dir=tmp_root))
    try:
        path = workdir / "model.glb"
        size = _spool_model(stream, path, settings.max_model_bytes)
        report = validate_mesh_file(path, file_type="glb")
        if report.status == ReportStatus.FAIL:
            raise InvalidInputError(
                "The edited model failed the file checks and was not saved.",
                details={"issues": [issue.to_dict() for issue in report.issues]},
            )
        number = (
            db.scalar(
                select(func.max(ModelVersion.version_number)).where(
                    ModelVersion.model_id == model.id
                )
            )
            or 0
        ) + 1
        key = model_asset_key(model.project_id, model.id, number, "model.glb")
        storage.save_file(key, path)
        try:
            version = ModelVersion(
                model_id=model.id,
                version_number=number,
                parent_version_id=parent.id,
                source=ModelVersionSource.EDITED,
                quality_mode=parent.quality_mode,
                provider_key=parent.provider_key,
                surface_provenance=parent.surface_provenance,
                stats={
                    **{k: report.metrics.get(k) for k in _STAT_KEYS},
                    **(
                        {"scale": parent.stats["scale"]}
                        if (parent.stats or {}).get("scale")
                        else {}
                    ),
                },
                notes=_edited_notes(parent, changes),
            )
            db.add(version)
            db.flush()
            mesh = Asset(
                project_id=model.project_id,
                model_version_id=version.id,
                kind=AssetKind.MESH,
                storage_key=key,
                mime_type=GLB_MIME,
                size_bytes=size,
                sha256=_sha256(path),
                meta={"format": "glb", "origin": "workspace_edit", "changes": changes},
            )
            db.add(mesh)
            db.add(
                QualityReport(
                    model_version_id=version.id,
                    status=report.status,
                    report_version=REPORT_VERSION,
                    metrics=report.metrics,
                    issues=[issue.to_dict() for issue in report.issues],
                )
            )
            db.flush()
            version.primary_asset_id = mesh.id
            model.current_version_id = version.id
            touch_project(db, model.project_id)
            db.commit()
        except BaseException:
            db.rollback()
            storage.delete(key)
            raise
    finally:
        shutil.rmtree(workdir, ignore_errors=True)
    return version


def update_model(db: Session, model_id: uuid.UUID, body: ModelUpdate) -> Model3D:
    model = get_model(db, model_id)
    if body.name is not None:
        model.name = body.name
    if body.current_version_id is not None:
        version = get_version(db, body.current_version_id)
        if version.model_id != model.id:
            raise InvalidInputError(
                "That version belongs to a different model.",
                details={"current_version_id": str(body.current_version_id)},
            )
        model.current_version_id = version.id
    touch_project(db, model.project_id)
    db.commit()
    return model


def list_versions(db: Session, model_id: uuid.UUID) -> list[ModelVersion]:
    get_model(db, model_id)
    return list(
        db.scalars(
            select(ModelVersion)
            .where(ModelVersion.model_id == model_id)
            .order_by(ModelVersion.version_number.desc())
        )
    )


# -- reading ------------------------------------------------------------------


def _asset(db: Session, version_id: uuid.UUID, kind: AssetKind) -> Asset | None:
    return db.scalar(
        select(Asset)
        .where(Asset.model_version_id == version_id, Asset.kind == kind)
        .order_by(Asset.created_at)
        .limit(1)
    )


def version_to_read(
    db: Session, registry: ProviderRegistry, version: ModelVersion
) -> ModelVersionRead:
    mesh = db.get(Asset, version.primary_asset_id) if version.primary_asset_id else None
    report = db.scalar(
        select(QualityReport)
        .where(QualityReport.model_version_id == version.id)
        .order_by(QualityReport.created_at.desc())
        .limit(1)
    )
    cls = registry.get(version.provider_key) if version.provider_key else None
    return ModelVersionRead(
        id=version.id,
        model_id=version.model_id,
        version_number=version.version_number,
        parent_version_id=version.parent_version_id,
        source=version.source,
        quality_mode=version.quality_mode,
        provider_key=version.provider_key,
        provider_display_name=cls.display_name if cls else version.provider_key,
        surface_provenance=version.surface_provenance,
        stats=version.stats,
        notes=version.notes,
        job_id=version.job_id,
        mesh=MeshFileRead(
            format=str(mesh.meta.get("format", "glb")),
            mime_type=mesh.mime_type,
            size_bytes=mesh.size_bytes,
            sha256=mesh.sha256,
        )
        if mesh
        else None,
        has_preview=_asset(db, version.id, AssetKind.PREVIEW_IMAGE) is not None,
        quality_report=QualityReportRead.model_validate(report) if report else None,
        created_at=version.created_at,
    )


def model_to_read(db: Session, registry: ProviderRegistry, model: Model3D) -> ModelRead:
    current = db.get(ModelVersion, model.current_version_id) if model.current_version_id else None
    count = (
        db.scalar(select(func.count(ModelVersion.id)).where(ModelVersion.model_id == model.id)) or 0
    )
    return ModelRead(
        id=model.id,
        project_id=model.project_id,
        name=model.name,
        created_at=model.created_at,
        updated_at=model.updated_at,
        current_version=version_to_read(db, registry, current) if current else None,
        version_count=count,
    )


def list_models(db: Session, project_id: uuid.UUID) -> list[Model3D]:
    get_project(db, project_id)
    return list(
        db.scalars(
            select(Model3D)
            .where(Model3D.project_id == project_id)
            .order_by(Model3D.created_at.desc())
        )
    )


def get_model(db: Session, model_id: uuid.UUID) -> Model3D:
    model = db.get(Model3D, model_id)
    if model is None:
        raise NotFoundError("Model not found.", details={"model_id": str(model_id)})
    return model


def get_version(db: Session, version_id: uuid.UUID) -> ModelVersion:
    version = db.get(ModelVersion, version_id)
    if version is None:
        raise NotFoundError("Model version not found.", details={"version_id": str(version_id)})
    return version


def version_file(db: Session, version_id: uuid.UUID, kind: AssetKind) -> tuple[ModelVersion, Asset]:
    version = get_version(db, version_id)
    asset = (
        db.get(Asset, version.primary_asset_id)
        if kind == AssetKind.MESH and version.primary_asset_id
        else _asset(db, version_id, kind)
    )
    if asset is None:
        raise NotFoundError("This version has no such file.")
    return version, asset


def download_filename(model: Model3D, version: ModelVersion, extension: str) -> str:
    slug = re.sub(r"[^A-Za-z0-9]+", "-", model.name).strip("-").lower() or "model"
    return f"{slug[:80]}-v{version.version_number}.{extension}"


def delete_model(db: Session, storage: StorageBackend, model_id: uuid.UUID) -> None:
    model = get_model(db, model_id)
    prefix = model_prefix(model.project_id, model.id)
    project_id = model.project_id
    # Break the models <-> model_versions cycle before the cascade.
    model.current_version_id = None
    db.flush()
    db.delete(model)
    touch_project(db, project_id)
    db.commit()
    try:
        storage.delete_prefix(prefix)
    except OSError:
        log.exception("failed to delete model files", extra={"prefix": prefix})
