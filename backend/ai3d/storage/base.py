from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO, Protocol


@dataclass(frozen=True, slots=True)
class StoredObject:
    key: str
    size_bytes: int
    sha256: str


class StorageBackend(Protocol):
    """Interface every storage backend implements.

    Keys are POSIX-style relative paths generated by the server
    (see ``ai3d.storage.keys``); user-supplied names never become keys.
    """

    name: str

    def save_file(self, key: str, source: Path) -> StoredObject:
        """Copy a local file into storage atomically."""
        ...

    def save_bytes(self, key: str, data: bytes) -> StoredObject: ...

    def open(self, key: str) -> BinaryIO: ...

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> None:
        """Delete one object; missing objects are ignored."""
        ...

    def delete_prefix(self, prefix: str) -> None:
        """Delete every object under a prefix (e.g. a whole project)."""
        ...

    def list_keys(self, prefix: str = "") -> list[str]:
        """Every key under a folder-style prefix ("" for all), sorted."""
        ...

    def local_path(self, key: str) -> Path | None:
        """Filesystem path for zero-copy serving, or None for remote backends."""
        ...

    def usage_bytes(self) -> int: ...

    def healthy(self) -> bool:
        """True when the backend can currently store objects."""
        ...
