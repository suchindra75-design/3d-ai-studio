#!/usr/bin/env node
// Regenerates packages/shared-types from the backend's OpenAPI schema.
//   pnpm gen:api          write files
//   pnpm gen:api --check  fail if the committed files are stale (used in CI)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const outDir = join(root, 'packages/shared-types');
const schemaPath = join(outDir, 'openapi.json');
const typesPath = join(outDir, 'src/openapi.gen.ts');
const check = process.argv.includes('--check');

const work = mkdtempSync(join(tmpdir(), 'ai3d-openapi-'));
try {
  const freshSchema = join(work, 'openapi.json');
  const freshTypes = join(work, 'openapi.gen.ts');
  execFileSync('uv', ['run', 'python', '-m', 'ai3d.openapi_export', freshSchema], {
    cwd: root,
    stdio: 'inherit',
  });
  execFileSync(
    join(root, 'node_modules/.bin/openapi-typescript'),
    [
      freshSchema,
      '--output',
      freshTypes,
      '--root-types',
      '--root-types-no-schema-prefix',
      // Response schemas mark always-present fields as required themselves; keep
      // request fields that have server defaults optional.
      '--default-non-nullable=false',
    ],
    { cwd: root, stdio: 'inherit' },
  );
  const header =
    '/* eslint-disable */\n// Generated by `pnpm gen:api` from the backend OpenAPI schema. Do not edit.\n\n';
  const types = header + readFileSync(freshTypes, 'utf8');
  const schema = readFileSync(freshSchema, 'utf8');

  if (check) {
    const stale =
      !existsSync(typesPath) ||
      readFileSync(typesPath, 'utf8') !== types ||
      readFileSync(schemaPath, 'utf8') !== schema;
    if (stale) {
      console.error('shared-types are out of date. Run `pnpm gen:api` and commit the result.');
      process.exit(1);
    }
    console.log('shared-types are up to date.');
  } else {
    writeFileSync(schemaPath, schema);
    writeFileSync(typesPath, types);
    console.log(`Wrote ${schemaPath} and ${typesPath}`);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
